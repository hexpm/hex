#!/bin/bash
set -e

if [[ -z "$1" ]]; then
  echo "Usage: vendor_mint.sh PATH_TO_MINT"
  exit 1
fi

dir=$1

if [[ -n "$(git -C $dir status --porcelain --untracked-files=no)" ]]; then
  echo "$dir has uncommitted changes"
  exit 1
fi

pushd $dir
mix compile
version=$(mix run -e 'IO.puts(Mix.Project.config[:version])')
shortref=$(git rev-parse --short HEAD)
popd

hpax_dir=$dir/deps/hpax
hpax_version=$(cat $hpax_dir/mix.exs | grep '@version' | head -1 | sed 's/.*"\(.*\)".*/\1/')

mint_copyright=$(grep -m1 '^Copyright' $dir/README.md)
hpax_copyright=$(grep -m1 '^Copyright' $hpax_dir/README.md)

if [[ -z "$mint_copyright" || -z "$hpax_copyright" ]]; then
  echo "Copyright notice not found in the Mint or HPAX README"
  exit 1
fi

license="Licensed under the Apache License, Version 2.0, modified by scripts/vendor_mint.sh"

rm -rf lib/hex/mint

# Keep the vendored modules out of Hex's documentation
function hide_moduledoc {
  perl -pi -e 's/^(\s*)\@moduledoc """/${1}\@moduledoc false\n${1}_ = """/' $1
}

for filename in $(find $dir/lib -type f -name '*.ex'); do
  target_filename=${filename#$dir/lib/}
  target_path=lib/hex/${target_filename}

  mkdir -p $(dirname $target_path)
  echo "# Vendored from mint v$version ($shortref), do not edit manually" > $target_path
  echo "# $mint_copyright" >> $target_path
  echo "# $license" >> $target_path
  echo >> $target_path
  cat $filename >> $target_path

  hide_moduledoc $target_path

  # Rename modules: Mint.* -> Hex.Mint.*
  sed -i.bak -E 's/Mint\.([A-Z{])/Hex.Mint.\1/g' $target_path
  rm $target_path.bak

  # Rename internal atom tags used in throw/catch and persistent_term keys
  sed -i.bak 's/{:mint,/{:hex_mint,/g' $target_path
  rm $target_path.bak

  # Use vendored Mint version in user agent
  sed -i.bak "s|Mix\.Project\.config()\[:version\]|\"$version\"|g" $target_path
  rm $target_path.bak
done

# Vendor Erlang shims
for filename in $(find $dir/src -type f -name '*.erl'); do
  basename=$(basename $filename)
  target_path=src/hex_${basename}

  echo "%% Vendored from mint v$version ($shortref), do not edit manually" > $target_path
  echo "%% $mint_copyright" >> $target_path
  echo "%% $license" >> $target_path
  echo >> $target_path
  cat $filename >> $target_path

  sed -i.bak 's/-module(mint_/-module(hex_mint_/g' $target_path
  rm $target_path.bak
done

# Update references to Erlang shims in vendored Elixir files
for filename in $(find lib/hex/mint -type f -name '*.ex'); do
  sed -i.bak 's/:mint_shims/:hex_mint_shims/g' $filename
  rm $filename.bak
done

# Vendor hpax (Mint dependency for HTTP/2 HPACK)
for filename in $(find $hpax_dir/lib -type f -name '*.ex'); do
  target_filename=${filename#$hpax_dir/lib/}
  target_path=lib/hex/mint/${target_filename}

  mkdir -p $(dirname $target_path)
  echo "# Vendored from hpax v$hpax_version, do not edit manually" > $target_path
  echo "# $hpax_copyright" >> $target_path
  echo "# $license" >> $target_path
  echo >> $target_path
  cat $filename >> $target_path

  hide_moduledoc $target_path

  # Rename modules: HPAX -> Hex.Mint.HPAX
  sed -i.bak 's/HPAX/Hex.Mint.HPAX/g' $target_path
  rm $target_path.bak
done

# Copy non-source files needed at compile time
cp $hpax_dir/lib/hpax/huffman_table lib/hex/mint/hpax/huffman_table

# Also rename HPAX references in vendored Mint files
for filename in $(find lib/hex/mint -type f -name '*.ex' ! -path '*/hpax*'); do
  sed -i.bak 's/HPAX/Hex.Mint.HPAX/g' $filename
  rm $filename.bak
done

# Elixir < 1.15 doesn't allow the pin operator in binary size specifiers and
# Elixir 1.20 warns when it's missing, rewrite `size(^var)` to
# `size(Hex.Mint.Compat.pin(var))`, which pins only on Elixir 1.15 and later
cat > lib/hex/mint/compat.ex <<'EOF'
# Generated by scripts/vendor_mint.sh, do not edit manually

defmodule Hex.Mint.Compat do
  @moduledoc false

  defmacro pin(var) do
    if Version.compare(System.version(), "1.15.0") == :lt do
      var
    else
      {:^, [], [var]}
    end
  end
end
EOF

for filename in $(grep -rlE 'size\(\^' lib/hex/mint); do
  perl -pi -e 's/size\(\^([a-z_][a-zA-Z0-9_]*)\)/size(Hex.Mint.Compat.pin($1))/g' $filename
  perl -0pi -e 's/^([ \t]*)(defmodule .* do\n)([ \t]*\@moduledoc false\n)?/$1$2$3\n$1  require Hex.Mint.Compat\n/mg' $filename
done

if grep -rnE 'size\([^)]*\^' lib/hex/mint; then
  echo "Pinned binary size specifiers left in vendored files"
  exit 1
fi
